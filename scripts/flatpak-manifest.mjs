// The Flatpak of OpenBand (issue #5): writes flatpak/it.openband.OpenBand.yml for a release, from the .deb
// files GitHub publishes for it (URL and SHA-256, x86_64 and aarch64), and adds the release to the
// AppStream metadata. The same manifest builds the .flatpak bundle in release.yml and is what a Flathub
// submission (github.com/flathub/flathub) carries.
//   node scripts/flatpak-manifest.mjs v0.6.35 [--out dir]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = 'iltempe/openband';
export const APP_ID = 'it.openband.OpenBand';

export function manifest({ version, debs }) {
  const src = (arch, a) => [`      - type: file`, `        url: ${a.url}`, `        sha256: ${a.sha256}`, `        dest-filename: openband.deb`, `        only-arches: [${arch}]`];
  return [
    `# Generated by scripts/flatpak-manifest.mjs for OpenBand ${version}: edit the script, not this file.`,
    `app-id: ${APP_ID}`,
    `runtime: org.freedesktop.Platform`,
    `runtime-version: '26.08'`,
    `sdk: org.freedesktop.Sdk`,
    `base: org.electronjs.Electron2.BaseApp`,
    `base-version: '26.08'`,
    `command: openband`,
    `separate-locales: false`,
    `finish-args:`,
    `  - --share=ipc`,
    `  - --socket=x11`,
    `  - --socket=wayland`,
    `  - --device=dri`,
    `  # Playback, recording and the microphone.`,
    `  - --socket=pulseaudio`,
    `  # MIDI keyboards and controllers (ALSA sequencer, /dev/snd/seq), audio interfaces.`,
    `  - --device=all`,
    `  # The online studio's engines, updates of fal/relay engines, publishing with the user's accounts.`,
    `  - --share=network`,
    `  # Songs and samples where people keep them; exports to Downloads.`,
    `  - --filesystem=xdg-music`,
    `  - --filesystem=xdg-download`,
    `  # The CLAP and VST3 plugins installed on the system.`,
    `  - --filesystem=/usr/lib/clap:ro`,
    `  - --filesystem=/usr/lib/vst3:ro`,
    `  - --filesystem=~/.clap:ro`,
    `  - --filesystem=~/.vst3:ro`,
    `  - --talk-name=org.freedesktop.Notifications`,
    `  - --env=OPENBAND_FLATPAK=1`,
    `modules:`,
    `  - name: openband`,
    `    buildsystem: simple`,
    `    sources:`,
    ...src('x86_64', debs.x86_64),
    ...(debs.aarch64 ? src('aarch64', debs.aarch64) : []),
    `      - type: file`,
    `        path: ${APP_ID}.desktop`,
    `      - type: file`,
    `        path: ${APP_ID}.metainfo.xml`,
    `      - type: script`,
    `        dest-filename: openband.sh`,
    `        commands:`,
    `          - exec zypak-wrapper /app/openband/openband "$@"`,
    `    build-commands:`,
    `      - bsdtar -xf openband.deb data.tar.xz`,
    `      - bsdtar -xf data.tar.xz ./opt/OpenBand ./usr/share/icons ./usr/share/mime`,
    `      - cp -a opt/OpenBand /app/openband`,
    `      # Electron's own sandbox helper: zypak replaces it inside the Flatpak.`,
    `      - rm -f /app/openband/chrome-sandbox`,
    `      - install -Dm755 openband.sh /app/bin/openband`,
    `      - install -Dm644 ${APP_ID}.desktop /app/share/applications/${APP_ID}.desktop`,
    `      - install -Dm644 ${APP_ID}.metainfo.xml /app/share/metainfo/${APP_ID}.metainfo.xml`,
    `      - install -Dm644 usr/share/icons/hicolor/512x512/apps/openband.png /app/share/icons/hicolor/512x512/apps/${APP_ID}.png`,
    `      - install -Dm644 usr/share/mime/packages/openband.xml /app/share/mime/packages/${APP_ID}.xml`,
    ``,
  ].join('\n');
}

/** The metainfo with this release first (once). */
export function withRelease(xml, { version, date }) {
  if (xml.includes(`<release version="${version}"`)) return xml;
  return xml.replace(/(<releases>\n)/, `$1    <release version="${version}" date="${date}">\n      <url type="details">https://github.com/${REPO}/releases/tag/v${version}</url>\n    </release>\n`);
}

async function main() {
  const tag = process.argv[2];
  if (!/^v\d+\.\d+\.\d+$/.test(tag ?? '')) throw new Error('usage: node scripts/flatpak-manifest.mjs vX.Y.Z [--out dir]');
  const out = process.argv.includes('--out') ? process.argv[process.argv.indexOf('--out') + 1] : path.join(root, 'flatpak');
  const version = tag.slice(1);
  const headers = { accept: 'application/vnd.github+json', ...(process.env.GH_TOKEN ? { authorization: `Bearer ${process.env.GH_TOKEN}` } : {}) };
  const res = await fetch(`https://api.github.com/repos/${REPO}/releases/tags/${tag}`, { headers });
  if (!res.ok) throw new Error(`GitHub: ${res.status} for ${tag}`);
  const rel = await res.json();
  const asset = (name) => {
    const a = rel.assets.find((x) => x.name === name);
    const sha256 = /^sha256:([0-9a-f]{64})$/.exec(a?.digest ?? '')?.[1];
    return a && sha256 ? { url: a.browser_download_url, sha256 } : null;
  };
  const debs = { x86_64: asset(`OpenBand-${version}-linux-amd64.deb`), aarch64: asset(`OpenBand-${version}-linux-arm64.deb`) };
  if (!debs.x86_64) throw new Error(`${tag} has no linux-amd64 .deb with a checksum yet`);
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, `${APP_ID}.yml`), manifest({ version, debs }));
  const meta = path.join(root, 'flatpak', `${APP_ID}.metainfo.xml`);
  const xml = withRelease(fs.readFileSync(meta, 'utf8'), { version, date: String(rel.published_at ?? new Date().toISOString()).slice(0, 10) });
  fs.writeFileSync(path.join(out, `${APP_ID}.metainfo.xml`), xml);
  if (out !== path.join(root, 'flatpak')) {
    fs.copyFileSync(path.join(root, 'flatpak', `${APP_ID}.desktop`), path.join(out, `${APP_ID}.desktop`));
  }
  console.log(`✓ ${path.join(out, `${APP_ID}.yml`)} (${Object.keys(debs).filter((k) => debs[k]).join(', ')})`);
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
